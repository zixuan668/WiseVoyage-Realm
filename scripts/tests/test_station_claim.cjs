const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

;(async () => {
  const root = path.resolve(__dirname, '../..')
  const storage = new Map()
  global.uni = {getStorageSync:key=>storage.get(key),setStorageSync:(key,value)=>storage.set(key,value),removeStorageSync:key=>storage.delete(key)}
  const source = fs.readFileSync(path.join(root,'app/common/station-claim.js'),'utf8')
  const claim = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))
  assert.equal(claim.parseClaim('ordinary launcher'),null)
  assert.equal(claim.parseClaim('https://example.org/not-a-route#claim='+'a'.repeat(43)),null)
  assert.equal(claim.parseClaim('abcd2345efgh').token,'ABCD2345EFGH')
  const origin='http://192.168.1.2:18000'
  const token='a'.repeat(43)
  assert.deepEqual(claim.parseClaim('zhiyouguide://claim?claim='+token+'&server='+encodeURIComponent(origin)),{token,origin})
  assert.deepEqual(claim.parseClaim('http://192.168.1.2:5173/m/receive#claim='+token+'&server='+encodeURIComponent(origin)),{token,origin})
  assert.deepEqual(claim.parseClaim('zhiyouguide://claim?manual=1&server='+encodeURIComponent(origin)),{token:'',origin})
  claim.saveClaim('ABCD2345EFGH')
  assert.equal(claim.pendingClaim().token,'ABCD2345EFGH')
  claim.clearPendingClaim()
  assert.equal(claim.pendingClaim(),null)
  const config=fs.readFileSync(path.join(root,'app/common/config.js'),'utf8')
  const validator=config.slice(config.indexOf('export function isLocalStationOrigin'),config.indexOf('export function setStationServerOrigin')).replace('export ','')
  const allowed=new Function(validator+';return isLocalStationOrigin')()
  for(const value of [origin,'http://10.198.63.153:18000','http://127.0.0.1:18000','http://172.16.0.1:18000'])assert(allowed(value),value)
  for(const value of ['http://8.8.8.8:18000','http://172.32.1.1:18000','http://192.168.1.2:80','http://user:pass@192.168.1.2:18000','http://192.168.999.2:18000','https://example.org'])assert(!allowed(value),value)
  const pages=JSON.parse(fs.readFileSync(path.join(root,'app/pages.json'),'utf8').replace(/\/\/[^\n]*/g,''))
  assert.equal(pages.pages[0].path,'pages/onboarding/onboarding')
  console.log('Station claim parsing, pending lifecycle, LAN restrictions and original startup: passed')
})().catch(error=>{console.error(error);process.exitCode=1})
